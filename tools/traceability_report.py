#!/usr/bin/env python3
"""Build a requirement -> test traceability matrix from pytest JUnit XML.

Every pytest test records its requirement IDs (from @pytest.mark.req) as a
JUnit <property name="requirements">. This tool joins those results with the
catalogue in tests/requirements.json.

Usage: python3 tools/traceability_report.py [--output reports/traceability.md] junit1.xml [junit2.xml ...]
Exit code: 0 when every requirement has >= 1 test and none failed, else 1.
"""

from __future__ import annotations

import argparse
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from simharness.requirements import load_requirements  # noqa: E402


def read_results(paths):
    """Yield (test id, outcome, [requirement ids]) for every <testcase>."""
    for path in paths:
        root = ET.parse(path).getroot()
        for case in root.iter("testcase"):
            if case.find("failure") is not None or case.find("error") is not None:
                outcome = "failed"
            elif case.find("skipped") is not None:
                outcome = "skipped"
            else:
                outcome = "passed"
            reqs = []
            for prop in case.iter("property"):
                if prop.get("name") == "requirements":
                    reqs = [r for r in prop.get("value", "").split(",") if r]
            yield f"{case.get('classname')}::{case.get('name')}", outcome, reqs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("junit", nargs="+", type=Path)
    parser.add_argument("--output", type=Path, default=Path("reports/traceability.md"))
    args = parser.parse_args()

    missing = [p for p in args.junit if not p.is_file()]
    if missing:
        print(f"ERROR: JUnit file(s) not found: {', '.join(map(str, missing))}", file=sys.stderr)
        return 1

    catalogue = load_requirements()
    by_req = defaultdict(list)
    totals = defaultdict(int)
    unknown = set()
    for test_id, outcome, reqs in read_results(args.junit):
        totals[outcome] += 1
        for req in reqs:
            if req not in catalogue:
                unknown.add(req)
            by_req[req].append((test_id, outcome))

    rows = []
    uncovered, failing = [], []
    for req_id, info in catalogue.items():
        tests = by_req.get(req_id, [])
        passed = sum(1 for _, o in tests if o == "passed")
        failed = sum(1 for _, o in tests if o == "failed")
        if not tests:
            result = "NOT COVERED"
            uncovered.append(req_id)
        elif failed:
            result = "FAIL"
            failing.append(req_id)
        elif passed == 0:
            result = "SKIPPED"
            uncovered.append(req_id)
        else:
            result = "PASS"
        examples = sorted({t.split("::")[-1].split("[")[0] for t, _ in tests})
        shown = ", ".join(f"`{e}`" for e in examples[:4]) + (f" (+{len(examples) - 4} more)" if len(examples) > 4 else "")
        rows.append(
            f"| {req_id} | {info['component']} | {info['text']} | {shown or '-'} | "
            f"{passed}/{len(tests)} | {'**' + result + '**' if result != 'PASS' else result} |"
        )

    lines = [
        "# Requirement Traceability Matrix",
        "",
        "Generated by `tools/traceability_report.py` from JUnit XML produced by the real test run.",
        "Requirements are demonstration requirements for an educational simulator.",
        "",
        f"Sources: {', '.join(p.name for p in args.junit)}",
        "",
        f"Test cases: {sum(totals.values())} total, {totals['passed']} passed, "
        f"{totals['failed']} failed, {totals['skipped']} skipped.",
        f"Requirements: {len(catalogue)} total, {len(catalogue) - len(uncovered) - len(failing)} passing, "
        f"{len(failing)} failing, {len(uncovered)} not covered.",
        "",
        "| Requirement | Component | Requirement text | Automated tests (function names) | Passed/Total | Result |",
        "|-------------|-----------|------------------|----------------------------------|--------------|--------|",
        *rows,
    ]
    if unknown:
        lines += ["", f"Unknown requirement IDs referenced by tests: {', '.join(sorted(unknown))}"]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Traceability: {len(catalogue)} requirements, {len(failing)} failing, {len(uncovered)} not covered "
          f"-> {args.output}")
    for req in failing:
        print(f"  FAIL         {req}")
    for req in uncovered:
        print(f"  NOT COVERED  {req}")
    return 1 if (failing or uncovered or unknown) else 0


if __name__ == "__main__":
    sys.exit(main())
