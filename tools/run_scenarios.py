#!/usr/bin/env python3
"""Run the fault-injection scenarios and write a readable report.

Usage (from the repository root):
    python3 tools/run_scenarios.py                    # scenarios/*.json
    python3 tools/run_scenarios.py --scenario-dir scenarios/negative_control

Writes reports/fault_injection_report.md and .json. Exit code 0 when every
scenario passes, 1 when any scenario fails, 2 on a harness/build error.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from simharness import REPO_ROOT, BuildError, Simulator, locate_simulator  # noqa: E402
from simharness.scenarios import SCENARIO_DIR, expand, load_scenarios, run_scenario  # noqa: E402


def describe_input(scenario: dict) -> str:
    parts = []
    if "config_patch" in scenario:
        parts.append(f"config patch {json.dumps(scenario['config_patch'])}")
    if "config_raw" in scenario:
        parts.append(f"raw config {scenario['config_raw']!r}")
    if scenario.get("config_missing"):
        parts.append("config file path does not exist")
    if scenario.get("script_missing"):
        parts.append("--script path does not exist")
    for line in expand(scenario.get("inject", [])):
        shown = line if len(line) <= 90 else line[:87] + "..."
        parts.append(f"`{shown.encode('unicode_escape').decode('ascii')}`")
    return "<br>".join(parts) if parts else "(none)"


def describe_expected(expect: dict) -> str:
    return "<br>".join(f"{key}: {json.dumps(value)}" for key, value in expect.items())


def describe_actual(actual: dict) -> str:
    keys = ["exit_code", "stdout_error_code", "initial_mode", "inject_status",
            "inject_error_codes", "final_mode", "active_violations"]
    return "<br>".join(f"{k}: {json.dumps(actual[k])}" for k in keys if k in actual)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--scenario-dir", type=Path, default=SCENARIO_DIR)
    parser.add_argument("--report-dir", type=Path, default=REPO_ROOT / "reports")
    parser.add_argument("--report-name", default="fault_injection_report")
    args = parser.parse_args()

    try:
        binary = locate_simulator()
    except BuildError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    sim = Simulator(binary, REPO_ROOT / "config" / "simulation_config.json")
    scenarios = load_scenarios(args.scenario_dir.resolve())
    if not scenarios:
        print(f"ERROR: no scenarios found in {args.scenario_dir}", file=sys.stderr)
        return 2

    results = [(scenario, run_scenario(sim, scenario)) for scenario in scenarios]
    failed = [r for _, r in results if not r.passed]

    print(f"Fault-injection scenarios ({args.scenario_dir}) using {binary}")
    print("-" * 78)
    for scenario, result in results:
        print(f"{'PASS' if result.passed else 'FAIL'}  {result.scenario_id:<6} {result.title}")
        for mismatch in result.mismatches:
            print(f"        - {mismatch}")
    print("-" * 78)
    print(f"{len(results) - len(failed)} passed, {len(failed)} failed, {len(results)} total")

    args.report_dir.mkdir(parents=True, exist_ok=True)
    md = [
        "# Fault-Injection Report",
        "",
        "Generated by `tools/run_scenarios.py` from the real `cubesat_sim` binary.",
        "Simulation only: thresholds are invented demonstration values.",
        "",
        f"**Result: {len(results) - len(failed)} passed, {len(failed)} failed, {len(results)} total**",
        "",
        "| ID | Scenario | Initial state | Input / fault injected | Expected | Actual | Result |",
        "|----|----------|---------------|------------------------|----------|--------|--------|",
    ]
    for scenario, result in results:
        md.append(
            f"| {result.scenario_id} | {result.title} | {scenario['initial_state']} | "
            f"{describe_input(scenario)} | {describe_expected(scenario['expect'])} | "
            f"{describe_actual(result.actual)} | {'PASS' if result.passed else '**FAIL**'} |"
        )
    md += ["", "## Diagnostics per scenario", ""]
    for scenario, result in results:
        md.append(f"### {result.scenario_id} - {result.title} ({'PASS' if result.passed else 'FAIL'})")
        md.append("")
        md.append(scenario["description"])
        md.append("")
        if result.mismatches:
            md.append("Mismatches:")
            md += [f"- {m}" for m in result.mismatches]
            md.append("")
        md.append("```text")
        md += result.diagnostics or ["(no diagnostic events)"]
        md.append("```")
        md.append("")

    md_path = args.report_dir / f"{args.report_name}.md"
    json_path = args.report_dir / f"{args.report_name}.json"
    md_path.write_text("\n".join(md), encoding="utf-8")
    json_path.write_text(
        json.dumps(
            [
                {
                    "id": r.scenario_id,
                    "title": r.title,
                    "file": s["_path"],
                    "requirements": s.get("requirements", []),
                    "passed": r.passed,
                    "mismatches": r.mismatches,
                    "actual": r.actual,
                    "diagnostics": r.diagnostics,
                }
                for s, r in results
            ],
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"Reports: {md_path} and {json_path}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
